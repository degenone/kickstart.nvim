-- Use actual tabs for Go (the Go standard)
vim.opt_local.expandtab = false

-- Set how many spaces a tab looks like (visual preference)
vim.opt_local.tabstop = 4
vim.opt_local.shiftwidth = 4
vim.opt_local.softtabstop = 4

-- Optional: Show a vertical line at 80 or 100 characters
-- to help keep your Go lines readable
vim.opt_local.colorcolumn = '100'
